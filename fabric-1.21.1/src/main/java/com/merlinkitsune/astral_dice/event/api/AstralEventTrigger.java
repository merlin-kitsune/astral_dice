package com.merlinkitsune.astral_dice.event.api;

/**
 * 事件触发方式(触发器)。事件注册时必须声明自己允许哪些来源。
 *
 * <p>2026-10-10 用户需求:需要<b>可注册的触发器</b>,首批覆盖 —— 大侦探主动技能、击杀隐匿调查目标、
 * 玩家使用「抽事件」物品 / 方块(两者<b>独立注册</b>)、以及预留的自定义来源。
 */
public enum AstralEventTrigger {
    /** 立牌主动技能(大侦探主动技能待重做,本轮不注册任何事件到该来源)。 */
    ACTIVE_SKILL,
    /** 击杀「隐匿调查」目标 —— <b>唯一</b>允许提升「调查阶段」事件阶级的来源。 */
    INVESTIGATION_KILL,
    /** 玩家使用「抽事件」物品。 */
    ITEM_USE,
    /** 玩家使用「抽事件」方块。 */
    BLOCK_USE,
    /** 自定义/其它来源(命令、脚本、后续事件系统扩展)。 */
    CUSTOM
}
